NOMINATIM_URL = "https://nominatim.openstreetmap.org/search"
USER_AGENT = "sberazs-bot-geobox-generator/1.0"


def fetch_bbox(region_name: str):
    params = {
        "q": f"{region_name}, Россия",
        "format": "json",
        "limit": 1,
        "countrycodes": "ru",
    }
    url = f"{NOMINATIM_URL}?{urllib.parse.urlencode(params)}"
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=15) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    if not data:
        return None
    # Nominatim отдаёт boundingbox как [min_lat, max_lat, min_lon, max_lon]
    # (строки) — приводим к формату проекта: (min_lon, min_lat, max_lon, max_lat).
    min_lat, max_lat, min_lon, max_lon = map(float, data[0]["boundingbox"])
    return (min_lon, min_lat, max_lon, max_lat)


def main():
    results = {}
    failed = []

    for i, region in enumerate(REGIONS, 1):
        print(f"[{i}/{len(REGIONS)}] {region}...", file=sys.stderr)
        try:
            bbox = fetch_bbox(region)
        except Exception as e:
            print(f"  ошибка: {e}", file=sys.stderr)
            bbox = None

        if bbox is None:
            failed.append(region)
        else:
            results[region] = bbox

        time.sleep(1.1)  # Nominatim: не чаще 1 запроса/сек

    if failed:
        print(f"\nНе удалось получить bbox для {len(failed)} регионов (пропущены):", file=sys.stderr)
        for r in failed:
            print(f"  - {r}", file=sys.stderr)
        print("Добавьте их вручную в geoboxes_local.py, если нужно.\n", file=sys.stderr)

    with open("app/geoboxes_local.py", "w", encoding="utf-8") as f:
        f.write(
            "# Сгенерировано generate_geoboxes.py через Nominatim (OpenStreetMap).\n"
            "# Проверьте координаты перед боевым запуском — крупные/сложной формы\n"
            "# регионы геокодер иногда отдаёт неточно. Формат: (min_lon, min_lat, max_lon, max_lat).\n"
            "GEOBOXES = {\n"
        )
        for name, (min_lon, min_lat, max_lon, max_lat) in results.items():
            f.write(f'    "{name}": ({min_lon}, {min_lat}, {max_lon}, {max_lat}),\n')
        f.write("}\n")

    print(f"\nГотово: {len(results)} регионов записано в app/geoboxes_local.py", file=sys.stderr)


if __name__ == "__main__":
    main()
